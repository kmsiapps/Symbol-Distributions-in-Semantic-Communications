def symbol_distribution(exps, test_name, captions, loader):
    '''
    See the distribution of the symbol generated by encoder of semantic model
    We assume symbol distribution as normal
    '''
    fig, axs = plt.subplots(ncols=len(exps), figsize=(4*len(exps)+2, 4))
    num_symbols = 16384 * 2
    GaussianDensityEstimator = GaussianDensityEstimation(num_symbols)
    KernelDensityEstimator = GaussianKernalDensityEstimation(chunk_size=512)
    VLCDensityEstimator = VLCPowerDensityEstimation()
    pdf_len = 200
    captions = iter(captions)
        
    if len(exps) == 1:
        axs = [axs]
    for exp, ax in zip(exps, axs):
        with torch.no_grad():
            model = loadModel(exp)
            
            # mini = float(torch.min(y))
            # maxi = float(torch.max(y))
            mini = -3
            maxi = 3
            # Image-wise Calcluation
            x = torch.arange(mini, maxi, (maxi-mini)/pdf_len, dtype=torch.float32, device='cuda')
            normal_PDFs = []
            symbol_PDFs = []
            VLCdist_PDFs = []
            PSNRs = []
            
            for img in loader:
                img = img.to('cuda')
                out = model(img)
                y = out['y']
                if isinstance(model, NTSCC_plus):
                    dB, C, H, W = y.shape
                    y = y.reshape(2, dB//2, C, H, W).permute(1, 0, 3, 4, 2).contiguous().reshape(dB//2, 2*H*W, C)
                    spatial_size = 2*H*W
                    
                    for img_idx in range(dB//2):
                        img_symbols = []
                        for ch_idx in range(spatial_size):
                            ch_len = out['indexes'][img_idx*spatial_size+ch_idx]
                            sym = y[img_idx, ch_idx, :ch_len]
                            img_symbols.append(sym)
                        break
                    img_symbol = torch.cat(img_symbols, dim=0).unsqueeze(0)
                else:
                    img_symbol = torch.concat([y.real, y.imag], dim=-1)
            
                # Normalize
                mu = torch.mean(img_symbol)
                sigma = torch.std(img_symbol)
                img_symbol = (img_symbol - mu)/sigma
                
                # normal_pdf = GaussianDensityEstimator.prob(x, 0, 1).flatten().cpu()
                # normal_PDFs.append(normal_pdf)
                
                symbol_pdf = KernelDensityEstimator.prob(img_symbol, x)
                symbol_pdf = symbol_pdf.reshape(-1, pdf_len).flatten().cpu()
                symbol_PDFs.append(symbol_pdf)
                
                # VLCdist_pdf = VLCDensityEstimator.prob(x).flatten().cpu()
                # VLCdist_PDFs.append(VLCdist_pdf)
            
                GaussianCrossEntropy = GaussianDensityEstimator.entropy(img_symbol, 0, 1).cpu()
                SymbolEntropy = KernelDensityEstimator.entropy(img_symbol).cpu()
                
                img_hat = out["x_hat"]
                mse = torch.mean((img - img_hat)**2)
                psnr = 10 * torch.log10(1 / mse)
                PSNRs.append(psnr.cpu())
                
            # Plot distribution
            symbol_PDF = np.mean(symbol_PDFs, axis=0)
            
            normal_PDF = GaussianDensityEstimator.prob(x, 0, 1).flatten().cpu()
            symbol_PDFs = np.concatenate(symbol_PDFs, axis=0)
            VLCdist_PDF = VLCDensityEstimator.prob(x).flatten().cpu()
            x = x.cpu()
            
            weight = 0.25
            intermediate_PDF = (weight) * VLCdist_PDF + (1 - weight) * normal_PDF
 
            PSNR = np.mean(PSNRs)
            # PSNR = 10 * np.log10(1 / PSNR)
            
            ax.plot(x, symbol_PDF, label='semantic symbols')
            ax.plot(x, normal_PDF, label=f'N({0}, {1})')
            ax.plot(x, VLCdist_PDF, label='VLC dist. 1/pi^2x^2 + 1')
            ax.plot(x, intermediate_PDF, label='Intermediate')
            ax.legend()
            ax.set_title(f'{next(captions)}\nPSNR: {PSNR:.2f}\nKLdiv: {float(GaussianCrossEntropy-SymbolEntropy):.4f}')
            # ax.set_title(f'{next(captions)}\nPSNR : {PSNR:.2f}')
            ax.set_ylabel('PDF')
            ax.set_ylim([0, 0.6])
    # fig.suptitle('PDF of semantic symbols and corresponding normal distribution\nH(x) + KL = GCE')
    fig.suptitle('PDF of normalized semantic symbol distributions and normal distribution')
    fig.tight_layout()
    fig.savefig(f'images/symbolGaussian_{test_name}.png', dpi=300)


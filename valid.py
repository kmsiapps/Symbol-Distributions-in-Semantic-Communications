    fig, axs = plt.subplots(ncols=len(exps), figsize=(4*len(exps)+2, 4))
    captions = iter(captions)
    pdf_len = 200
    KernelDensityEstimator = GaussianKernalDensityEstimation(chunk_size=24)
        
    if len(exps) == 1:
        axs = [axs]
    for exp, ax in zip(exps, axs):
        with torch.no_grad():
            model = loadModel(exp)
            powers = []
            for img in loader:
                img = img.to('cuda')
                out = model(img)
                y = out['y']
                
                powers.append(torch.mean(y**2, dim=1))
                
            powers = torch.cat(powers).reshape(1, -1)
            mini = float(torch.min(powers))
            maxi = float(torch.max(powers))
            x = torch.arange(mini, maxi, (maxi-mini)/pdf_len, dtype=torch.float32, device='cuda')
            power_pdf = KernelDensityEstimator.prob(powers, x)
            x = x.cpu()
            
            # Plot distribution
            ax.plot(x, power_pdf, label='Powers')

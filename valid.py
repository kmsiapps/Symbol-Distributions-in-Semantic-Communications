            def student_t_pdf(x, nu):
                if nu <= 2:
                    raise ValueError("Degrees of freedom (nu) must be greater than 2 for a finite variance.")
                
                # Scale factor to normalize the variance to 1
                scale_factor = np.sqrt((nu - 2) / nu)
                
                # Normalization constant for the generalized t-distribution
                normalization_constant = gamma((nu + 1) / 2) / (np.sqrt(nu * np.pi) * gamma(nu / 2) * scale_factor)
                
                return normalization_constant * (1 + (x / scale_factor) ** 2 / nu) ** (-(nu + 1) / 2)

